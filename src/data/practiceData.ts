// Fixed teacher questions helper:
// - Keeps Unscramble the Word questions and tiles in exact teacher-approved order
// - Keeps Vocabulary in Context in exact pedagogical order (Personality -> Nationality -> Country vs Nationality)
// - Randomizes Multiple Choice order where appropriate
export function getActivityQuestions(activityId: VocabActivityId, randomize = true): PracticeQuestion[] {
  // Activity C: Fixed teacher order, no runtime reshuffling
  if (activityId === 'unscramble-word') {
    return [...OFFICIAL_UNSCRAMBLE_WORD_QUESTIONS];
  }

  // Activity D: Fixed pedagogical progression (1-8 Personality, 9-16 Nationality, 17-20 Country vs Nationality)
  if (activityId === 'vocab-context') {
    return [...OFFICIAL_VOCAB_CONTEXT_QUESTIONS];
  }

  const list = TEMPORARY_PRACTICE_QUESTIONS[activityId] || [];

  if (!randomize) {
    return [...list];
  }

  // 1. Randomize order of questions
  const shuffledQuestions = [...list].sort(() => Math.random() - 0.5);

  // 2. Randomize order of options (A/B/C/D) where applicable
  return shuffledQuestions.map((q) => {
    if (q.options && q.options.length > 0) {
      const shuffledOptions = [...q.options].sort(() => Math.random() - 0.5);
      return {
        ...q,
        options: shuffledOptions,
      };
    }
    return q;
  });
}
